#!/usr/bin/env python3
"""Convert original T2K Jaguar voice samples (signed 8-bit PCM) to 4-bit
CH3 wave buffers for the GBC player.

Source files: third_party/t2k-vox/*.bin
from mwenge/tempest2k src/sounds/samples 22–25, 27–28.
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "third_party" / "t2k-vox"
GEN = ROOT / "gen"
BLOB_BANK0 = 3
IN_RATE = 22050
OUT_RATE = 8192

CLIPS = [
    ("excellent", "excellent.bin"),
    ("zapper", "zapper.bin"),
    ("yes", "yes.bin"),
    ("oneup", "oneup.bin"),
    ("sexy1", "sexy1.bin"),
    ("sexy2", "sexy2.bin"),
]


def s8(b: int) -> int:
    return b - 256 if b > 127 else b


def convert(path: Path) -> bytes:
    sig = [s8(x) for x in path.read_bytes()]
    thr = 10
    a, z = 0, len(sig)
    while a < z and abs(sig[a]) < thr:
        a += 1
    while z > a and abs(sig[z - 1]) < thr:
        z -= 1
    sig = sig[a:z] or [0]
    n = max(32, int(len(sig) * OUT_RATE / IN_RATE))
    out = []
    for i in range(n):
        x = i * IN_RATE / OUT_RATE
        j = int(x)
        f = x - j
        u = sig[j] if j < len(sig) else 0
        v = sig[j + 1] if j + 1 < len(sig) else 0
        out.append(u * (1 - f) + v * f)
    # Peak-normalize is too quiet: T2K speech sits ~7% FS with rare spikes.
    # Map the 70th-percentile |s| onto the full 4-bit CH3 range and clip.
    abs_sorted = sorted(abs(s) for s in out)
    p70 = abs_sorted[int(len(abs_sorted) * 0.70)]
    p70 = max(p70, 1.0)
    nib = []
    used = [0] * 16
    for s in out:
        q = int(round(s / p70 * 7.0 + 8.0))
        if q < 0:
            q = 0
        if q > 15:
            q = 15
        nib.append(q)
        used[q] += 1
    print(f"  4bit hist p70={p70:.1f} {used}")
    while len(nib) % 32:
        nib.append(8)
    packed = bytearray()
    for i in range(0, len(nib), 2):
        packed.append(((nib[i] & 15) << 4) | (nib[i + 1] & 15))
    return bytes(packed)


def main() -> None:
    GEN.mkdir(exist_ok=True)
    blob_len = (GEN / "blob.bin").stat().st_size if (GEN / "blob.bin").exists() else 0
    tunes_len = (GEN / "tunes.bin").stat().st_size if (GEN / "tunes.bin").exists() else 0
    base = BLOB_BANK0 * 0x4000 + blob_len + tunes_len
    blob = bytearray()
    meta = []
    for name, fn in CLIPS:
        p = SRC / fn
        if not p.exists():
            raise SystemExit(f"missing {p}")
        data = convert(p)
        bank_off = (base + len(blob)) % 0x4000
        if bank_off and bank_off + len(data) > 0x4000:
            blob += b"\x00" * (0x4000 - bank_off)
        meta.append((name, len(blob), len(data)))
        blob += data
        print(f"{name:12} {len(data):5} bytes  (~{len(data) * 2 / OUT_RATE:.2f}s)")
    (GEN / "voices.bin").write_bytes(blob)
    banks, addrs, lens = [], [], []
    lines = [
        "/* generated by tools/vox.py from original T2K Jaguar voice samples */",
        "#ifndef VOICES_H",
        "#define VOICES_H",
        "#include <stdint.h>",
        f"#define NVOICES {len(meta)}",
        "static const uint8_t vox_bank[NVOICES] = {",
    ]
    for name, off, ln in meta:
        rom = base + off
        banks.append(str(rom // 0x4000))
        addrs.append(f"0x{0x4000 + (rom % 0x4000):04X}")
        lens.append(str(ln))
        print(f"  {name:12} bank {rom // 0x4000} addr 0x{0x4000 + rom % 0x4000:04X} len {ln}")
    lines += [
        "    " + ", ".join(banks) + " };",
        "static const uint16_t vox_addr[NVOICES] = {",
        "    " + ", ".join(addrs) + " };",
        "static const uint16_t vox_len[NVOICES] = {",
        "    " + ", ".join(lens) + " };",
        "#endif",
        "",
    ]
    (GEN / "voices.h").write_text("\n".join(lines))
    print(f"wrote gen/voices.bin {len(blob)} bytes")


if __name__ == "__main__":
    main()
